// 灰色选择事件：中晚年（第五十九轮）
//
// 为什么要有这一组：实测 seed 6 / warden / 寒门那唯一活过 1644 的一局，
// 1644-05 到 1645-08 播完 18 张卡之后 **276 个月一张也没有**，
// 直到 1669 年年满七十被《寿终正寝》收走。年窗全部在 1645 前关完，
// 而按公元年设下限又会撞上 `audit-repeatable-gating`（可重复支线最晚 1630 开门）——
// 所以这一组统一用**年岁**开门：玩家在顶栏看得见「年方X岁」，
// 而年岁与"天下发生了什么"无关，四十六岁的人在哪一年都是四十六岁。
//
// 三条口径：
//   1. 支线池是**可重复**的，所以每一张都要能被岁月重新找上门：
//      它们没有不重复的剧情任务，只有年复一年的老去。
//   2. 致仕那条是真收笔：选项走 `special.type='ending'`，
//      结局格子仍是图鉴里的《致仕善终》（`ending_registry` 里有别名）。
//      另外两条不是"假选项"——留任与告病各有明码代价，都可以继续玩下去。
//   3. 加钱、加体质都要有别的账：这一组不卖无代价的养生，也不发无代价的体面。
// ==========================================

